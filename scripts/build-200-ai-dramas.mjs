let globalIndex = 0;
const allDramas = [];

// Генерируем 215 уникальных сериалов
for (const genre of GENRES) {
  for (const title of genre.titles) {
    globalIndex++;
    const dramaId = `drama-ai-${globalIndex.toString().padStart(3, "0")}`;

    // Выбираем 2-4 последовательные серии
    const epCount = 2 + (globalIndex % 3); // 2, 3 или 4 серии
    const episodes = [];

    const baseVideoIdx = (globalIndex * 2) % VERIFIED_VIDEOS.length;

    for (let e = 1; e <= epCount; e++) {
      const v = VERIFIED_VIDEOS[(baseVideoIdx + e - 1) % VERIFIED_VIDEOS.length];
      const epId = `ep-${dramaId}-${e}`;
      const epTitle =
        e === 1
          ? `Часть 1: Начало истории и завязка (серии 1–12)`
          : e === epCount
          ? `Часть ${e}: Финал и возмездие (серии ${12 * (e - 1)}–${12 * e})`
          : `Часть ${e}: Неожиданный поворот событий (серии ${12 * (e - 1)}–${12 * e})`;

      episodes.push({
        id: epId,
        dramaId,
        episodeNumber: e,
        title: epTitle,
        description: `Официальная русская озвучка. Китайский вертикальный ИИ-сериал: ${title}. Серия ${e} из ${epCount}.`,
        videoId: v.id,
        sourcePlatform: "youtube",
        durationSeconds: v.dur,
        thumbnailUrl: `https://i.ytimg.com/vi/${v.id}/hqdefault.jpg`,
        isAvailable: true,
        createdAt: "2026-10-18T12:00:00Z",
      });
    }

    const firstVid = episodes[0].videoId;
    const views = 50000 + ((globalIndex * 9871) % 450000);

    allDramas.push({
      id: dramaId,
      title: title,
      originalTitle: `AI Mini-Series #${globalIndex}: ${title} (AI Drama)`,
      description: `Захватывающий китайский вертикальный AI-сериал с полной русской озвучкой, полностью сгенерированный передовыми нейросетями. Тематика: ${genre.themes}. Все серии подряд с автопродолжением.`,
      coverUrl: `https://i.ytimg.com/vi/${firstVid}/hqdefault.jpg`,
      bannerUrl: `https://i.ytimg.com/vi/${firstVid}/hqdefault.jpg`,
      tags: ["AI-сериал", "Русская озвучка", genre.tag, "Китайские дорамы"],
      isAiGenerated: true,
      language: "ru",
      hasRussianVoiceover: true,
      hasRussianSubtitles: true,
      sourceType: "youtube_playlist",
      sourceId: `neiroserials-ai-${globalIndex}`,
      totalEpisodes: epCount,
      status: "completed",
      viewCount: views,
      isPublished: true,
      createdAt: new Date(Date.now() - globalIndex * 3600 * 1000 * 4).toISOString(),
      updatedAt: new Date().toISOString(),
      episodes,
    });
  }
}

