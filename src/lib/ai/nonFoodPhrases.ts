/** Нормализация строкового значения причины в типизированный enum */
export function normalizeNonFoodReason(val: unknown): NonFoodReason {
  if (typeof val !== "string") return "other";
  const s = val.toLowerCase().trim();
  if (
    s.includes("person") ||
    s.includes("human") ||
    s.includes("face") ||
    s.includes("selfie") ||
    s.includes("человек") ||
    s.includes("лицо") ||
    s.includes("селфи") ||
    s.includes("парень") ||
    s.includes("девушк") ||
    s.includes("пользовател")
  ) {
    return "person";
  }
  if (
    s.includes("pet") ||
    s.includes("cat") ||
    s.includes("dog") ||
    s.includes("puppy") ||
    s.includes("kitten") ||
    s.includes("animal") ||
    s.includes("кот") ||
    s.includes("собак") ||
    s.includes("животн") ||
    s.includes("пес") ||
    s.includes("пёс") ||
    s.includes("питом") ||
    s.includes("щенок") ||
    s.includes("котен") ||
    s.includes("котён") ||
    s.includes("звер")
  ) {
    return "pet";
  }
  if (
    s.includes("gadget") ||
    s.includes("tech") ||
    s.includes("phone") ||
    s.includes("laptop") ||
    s.includes("device") ||
    s.includes("комп") ||
    s.includes("ноутбук") ||
    s.includes("смартфон") ||
    s.includes("девайс") ||
    s.includes("телефон") ||
    s.includes("техник") ||
    s.includes("экран") ||
    s.includes("монитор") ||
    s.includes("клавиатур") ||
    s.includes("наушник")
  ) {
    return "gadget";
  }
  if (
    s.includes("plate") ||
    s.includes("empty") ||
    s.includes("пуст") ||
    s.includes("посуд") ||
    s.includes("чашк") ||
    s.includes("кружк")
  ) {
    return "empty_plate";
  }
  if (
    s.includes("blur") ||
    s.includes("dark") ||
    s.includes("размыт") ||
    s.includes("темн") ||
    s.includes("смаз") ||
    s.includes("нечетк") ||
    s.includes("нечётк")
  ) {
    return "blur";
  }
  if (
    s.includes("object") ||
    s.includes("item") ||
    s.includes("предмет") ||
    s.includes("вещь") ||
    s.includes("одежд") ||
    s.includes("мебел") ||
    s.includes("обув") ||
    s.includes("ключ")
  ) {
    return "inanimate_object";
  }
  return "other";
}

/** Получить случайный остроумный ответ для указанной категории */
export function getRandomNonFoodResponse(reason: NonFoodReason): string {
  const list = NON_FOOD_RESPONSES[reason] || NON_FOOD_RESPONSES.other;
  const index = Math.floor(Math.random() * list.length);
  return list[index] || list[0];
}

/** Получить визуальные метаданные для категории */
export function getNonFoodMeta(reason: NonFoodReason): NonFoodMeta {
  return NON_FOOD_META[reason] || NON_FOOD_META.other;
}
